#!/usr/bin/env python3
"""Regenerates `kinds.rs` from HHVM's generated syntax definitions.

    python3 src/parser/cst/generate.py   # from the hakana-core directory

The lossless syntax tree the linters and the formatter read has the node
kinds, child order and token kinds of HHVM's full-fidelity tree. This reads
those from the HHVM checkout so that a new HHVM revision is one command away;
the parser then has to learn to produce whatever is new (the differential
tests say what).
"""
import os
import re
import subprocess

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..")
PARSER = os.path.join(ROOT, "third-party", "hhvm", "hphp", "hack", "src", "parser")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "kinds.rs")


def read(name):
    with open(os.path.join(PARSER, name)) as f:
        return f.read()


def enum_variants(src, enum):
    body = src[src.index("pub enum " + enum) :]
    body = body[body.index("{") + 1 : body.index("\n}")]
    out = []
    for line in body.splitlines():
        line = line.split("//")[0].strip().rstrip(",")
        if not line:
            continue
        out.append(re.sub(r"\s*=.*", "", line))
    return out


def main():
    syntax_kinds = [k for k in enum_variants(read("syntax_kind.rs"), "SyntaxKind")]
    token_src = read("token_kind.rs")
    token_kinds = enum_variants(token_src, "TokenKind")
    trivia_kinds = enum_variants(read("trivia_kind.rs"), "TriviaKind")

    # Token text: the `to_string` table.
    to_string = token_src[token_src.index("pub fn to_string") :]
    to_string = to_string[: to_string.index("\n    }\n")]
    token_text = dict(re.findall(r'TokenKind::(\w+) => "((?:[^"\\]|\\.)*)"', to_string))

    # Children of each node kind, in order.
    variant_src = read("syntax_by_ref/syntax_variant_generated.rs")
    children = {}
    for name, body in re.findall(
        r"pub struct (\w+)Children<'a, T, V> \{(.*?)\n\}", variant_src, re.S
    ):
        children[name] = re.findall(r"pub (\w+): Syntax", body)

    nodes = [k for k in syntax_kinds if k not in ("Missing", "Token(TokenKind)", "SyntaxList")]
    missing = [k for k in nodes if k not in children]
    assert not missing, missing

    o = []
    o.append("// @generated by src/parser/cst/generate.py from HHVM's syntax definitions.")
    o.append("// Do not edit; run the script again after updating the HHVM submodule.")
    o.append("")
    o.append("/// The kind of a node of the lossless syntax tree.")
    o.append("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]")
    o.append("pub enum SyntaxKind {")
    o.append("    Missing,")
    o.append("    Token(TokenKind),")
    o.append("    SyntaxList,")
    for k in nodes:
        o.append(f"    {k},")
    o.append("}")
    o.append("")
    o.append("impl SyntaxKind {")
    o.append("    /// The names of the children of a node of this kind, in order. Empty for")
    o.append("    /// tokens, missing nodes and lists.")
    o.append("    pub fn children(self) -> &'static [&'static str] {")
    o.append("        match self {")
    o.append("            SyntaxKind::Missing | SyntaxKind::Token(_) | SyntaxKind::SyntaxList => &[],")
    for k in nodes:
        names = ", ".join(f'"{c}"' for c in children[k])
        o.append(f"            SyntaxKind::{k} => &[{names}],")
    o.append("        }")
    o.append("    }")
    o.append("")
    o.append("    /// The node kind called `name` (not `Missing`, `Token` or `SyntaxList`).")
    o.append("    pub fn from_name(name: &str) -> Option<SyntaxKind> {")
    o.append("        Some(match name {")
    for k in nodes:
        o.append(f'            "{k}" => SyntaxKind::{k},')
    o.append("            _ => return None,")
    o.append("        })")
    o.append("    }")
    o.append("")
    o.append("    pub fn name(self) -> &'static str {")
    o.append("        match self {")
    o.append('            SyntaxKind::Missing => "Missing",')
    o.append('            SyntaxKind::Token(_) => "Token",')
    o.append('            SyntaxKind::SyntaxList => "SyntaxList",')
    for k in nodes:
        o.append(f'            SyntaxKind::{k} => "{k}",')
    o.append("        }")
    o.append("    }")
    o.append("}")
    o.append("")
    o.append("/// The kind of a token.")
    o.append("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]")
    o.append("#[allow(non_camel_case_types)]")
    o.append("#[repr(u8)]")
    o.append("pub enum TokenKind {")
    for k in token_kinds:
        o.append(f"    {k},")
    o.append("}")
    o.append("")
    o.append("impl TokenKind {")
    o.append("    /// Every token kind, in declaration order (which is HHVM's numbering).")
    o.append(f"    pub const ALL: [TokenKind; {len(token_kinds)}] = [")
    for k in token_kinds:
        o.append(f"        TokenKind::{k},")
    o.append("    ];")
    o.append("")
    o.append("    /// The text of a keyword or punctuation token, or a description of a")
    o.append("    /// token whose text varies (`name`, `variable`, ...).")
    o.append("    pub fn to_string(self) -> &'static str {")
    o.append("        match self {")
    for k in token_kinds:
        o.append(f'            TokenKind::{k} => "{token_text[k]}",')
    o.append("        }")
    o.append("    }")
    o.append("")
    # Fixed-text tokens: HHVM's `from_string` table, arm for arm.
    from_string = token_src[token_src.index("pub fn from_string") :]
    from_string = from_string[from_string.index("match keyword {") : from_string.index("_ => None")]
    arms = re.findall(
        r'b"([^"]+)"( if !only_reserved)? => Some\(TokenKind::(\w+)\)', from_string
    )
    o.append("    /// The keyword or punctuation token spelled `text`, if any. With")
    o.append("    /// `only_reserved`, keywords that can also be used as names are left out.")
    o.append("    pub fn from_string(text: &[u8], only_reserved: bool) -> Option<TokenKind> {")
    o.append("        match text {")
    for text, guard, kind in arms:
        o.append(f'            b"{text}"{guard} => Some(TokenKind::{kind}),')
    o.append("            _ => None,")
    o.append("        }")
    o.append("    }")
    o.append("")
    o.append("}")
    o.append("")
    o.append("/// The kind of a piece of trivia: whitespace and comments around tokens.")
    o.append("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]")
    o.append("#[repr(u8)]")
    o.append("pub enum TriviaKind {")
    for k in trivia_kinds:
        o.append(f"    {k},")
    o.append("}")
    o.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(o))
    subprocess.run(["rustfmt", "--edition", "2024", OUT], check=False)
    print(f"{len(nodes)} node kinds, {len(token_kinds)} token kinds -> {OUT}")

    # The typed view of the tree (`hakana-syntax`): one struct of named
    # children per node kind, as HHVM's API has them.
    t = []
    t.append("// @generated by src/parser/cst/generate.py from HHVM's syntax definitions.")
    t.append("// Do not edit; run the script again after updating the HHVM submodule.")
    t.append("")
    t.append("use hakana_parser::cst::SyntaxKind;")
    t.append("")
    t.append("use super::syntax::Syntax;")
    t.append("")
    t.append("/// What a node is, with its children.")
    t.append("#[derive(Debug, Clone)]")
    t.append("pub enum SyntaxVariant<'a, T, V> {")
    t.append("    Token(T),")
    t.append("    Missing,")
    t.append("    SyntaxList(&'a [Syntax<'a, T, V>]),")
    for k in nodes:
        t.append(f"    {k}(&'a {k}Children<'a, T, V>),")
    t.append("}")
    t.append("")
    for k in nodes:
        # `repr(C)` so that the children can also be read as a slice.
        t.append("#[derive(Debug, Clone)]")
        t.append("#[repr(C)]")
        t.append(f"pub struct {k}Children<'a, T, V> {{")
        for c in children[k]:
            t.append(f"    pub {c}: Syntax<'a, T, V>,")
        t.append("}")
        t.append("")
    t.append("impl<'a, T, V> SyntaxVariant<'a, T, V> {")
    t.append("    /// Wraps the children of a node of the given kind, which must be as")
    t.append("    /// many as the kind has.")
    t.append("    pub(crate) fn from_children(kind: SyntaxKind, children: &'a [Syntax<'a, T, V>]) -> Self {")
    t.append("        assert_eq!(children.len(), kind.children().len());")
    t.append("        let first = children.as_ptr();")
    t.append("        // SAFETY: each `...Children` struct is `repr(C)` and consists of")
    t.append("        // exactly `kind.children().len()` fields of type `Syntax`, so it")
    t.append("        // has the layout of an array of that many; the length was checked.")
    t.append("        unsafe {")
    t.append("            match kind {")
    t.append("                SyntaxKind::Missing | SyntaxKind::Token(_) | SyntaxKind::SyntaxList => {")
    t.append('                    unreachable!("not a node with named children")')
    t.append("                }")
    for k in nodes:
        t.append(f"                SyntaxKind::{k} => SyntaxVariant::{k}(&*(first as *const {k}Children<'a, T, V>)),")
    t.append("            }")
    t.append("        }")
    t.append("    }")
    t.append("")
    t.append("    /// The kind of a node that is not a token.")
    t.append("    pub(crate) fn node_kind(&self) -> Option<SyntaxKind> {")
    t.append("        Some(match self {")
    t.append("            SyntaxVariant::Token(_) => return None,")
    t.append("            SyntaxVariant::Missing => SyntaxKind::Missing,")
    t.append("            SyntaxVariant::SyntaxList(_) => SyntaxKind::SyntaxList,")
    for k in nodes:
        t.append(f"            SyntaxVariant::{k}(_) => SyntaxKind::{k},")
    t.append("        })")
    t.append("    }")
    t.append("")
    t.append("    /// The children of the node, in order.")
    t.append("    pub fn children(&self) -> &'a [Syntax<'a, T, V>] {")
    t.append("        // SAFETY: see `from_children`.")
    t.append("        unsafe {")
    t.append("            match *self {")
    t.append("                SyntaxVariant::Token(_) | SyntaxVariant::Missing => &[],")
    t.append("                SyntaxVariant::SyntaxList(items) => items,")
    for k in nodes:
        n = len(children[k])
        t.append(f"                SyntaxVariant::{k}(x) => std::slice::from_raw_parts(x as *const {k}Children<'a, T, V> as *const Syntax<'a, T, V>, {n}),")
    t.append("            }")
    t.append("        }")
    t.append("    }")
    t.append("}")
    t.append("")
    typed = os.path.normpath(
        os.path.join(ROOT, "src", "syntax", "syntax_by_ref", "syntax_variant_generated.rs")
    )
    with open(typed, "w") as f:
        f.write("\n".join(t))
    subprocess.run(["rustfmt", "--edition", "2024", typed], check=False)
    print(f"typed view -> {typed}")


if __name__ == "__main__":
    main()
